-- glxt-api procedure transaction rollback probe
-- Run as the same Oracle schema used by the API connection.
-- This script drops/recreates only the CODEX_PROC_ROLLBACK_TEST_* objects below.

BEGIN
  EXECUTE IMMEDIATE 'DROP PROCEDURE PROC_ROLLBACK_PROBE_CHECK';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -4043 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'DROP PROCEDURE PROC_ROLLBACK_PROBE_CLEAN';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -4043 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'DROP PROCEDURE PROC_ROLLBACK_PROBE_FAIL';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -4043 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE CODEX_PROC_ROLLBACK_TEST PURGE';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

CREATE TABLE CODEX_PROC_ROLLBACK_TEST (
  REQUEST_ID  VARCHAR2(64) PRIMARY KEY,
  CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

COMMENT ON TABLE CODEX_PROC_ROLLBACK_TEST IS 'Temporary glxt-api procedure transaction rollback test table';
COMMENT ON COLUMN CODEX_PROC_ROLLBACK_TEST.REQUEST_ID IS 'Unique ID supplied by the Postman test';
COMMENT ON COLUMN CODEX_PROC_ROLLBACK_TEST.CREATED_AT IS 'Insert timestamp, expected row to be rolled back';

-- Writes one row and then fails. There is intentionally no COMMIT here.
CREATE OR REPLACE PROCEDURE PROC_ROLLBACK_PROBE_FAIL (
  P_TEST_ID IN VARCHAR2
)
AS
BEGIN
  INSERT INTO CODEX_PROC_ROLLBACK_TEST (REQUEST_ID) VALUES (P_TEST_ID);
  RAISE_APPLICATION_ERROR(-20081, 'ROLLBACK_PROBE_FORCED_FAILURE');
END;
/

-- Used by the second Postman request to verify the failed call left no row.
CREATE OR REPLACE PROCEDURE PROC_ROLLBACK_PROBE_CHECK (
  P_TEST_ID IN VARCHAR2,
  P_ROW_COUNT OUT NUMBER
)
AS
BEGIN
  SELECT COUNT(*)
    INTO P_ROW_COUNT
    FROM CODEX_PROC_ROLLBACK_TEST
   WHERE REQUEST_ID = P_TEST_ID;
END;
/

-- Optional manual cleanup. The test IDs are unique; this does not truncate the table.
CREATE OR REPLACE PROCEDURE PROC_ROLLBACK_PROBE_CLEAN (
  P_TEST_ID IN VARCHAR2
)
AS
BEGIN
  DELETE FROM CODEX_PROC_ROLLBACK_TEST WHERE REQUEST_ID = P_TEST_ID;
END;
/

